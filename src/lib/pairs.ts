export function intervalSeconds(tf: Timeframe): number {
  if (tf === "5m") return 300;
  if (tf === "15m") return 900;
  if (tf === "1h") return 3600;
  return 14400;
}

export function barsPerDay(tf: Timeframe): number {
  if (tf === "5m") return 288;
  if (tf === "15m") return 96;
  if (tf === "1h") return 24;
  return 6;
}
